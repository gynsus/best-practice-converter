def map_nekond(value: str, mapping: dict[str, str]) -> tuple[str, str]:
    """Значение отметки некондиции -> (качество, текст ошибки).

    Пустое значение -> «Стандарт». Неизвестное значение -> «Стандарт» +
    текст в колонку «Ошибка» (ТЗ 3.2.18) — чтобы не потерять сигнал молча.
    """
    v = (value or "").strip()
    if not v:
        return QUALITY_STANDARD, ""
    if v in mapping:
        return mapping[v], ""
    low = v.casefold()
    for key, quality in mapping.items():
        if key.casefold() in low:
            return quality, ""
    return QUALITY_STANDARD, f"неизвестная отметка некондиции: {v}"
