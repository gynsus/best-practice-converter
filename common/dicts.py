# --- Валюты (ТЗ табл. 1). Ключ — нормализованное значение поставщика. ---
_CURRENCY = {
    "RUB": "RUB", "RUR": "RUB", "РУБ": "RUB", "РУБЛИ": "RUB", "₽": "RUB",
    "USD": "USD", "$": "USD", "ДОЛЛ": "USD",
    "EUR": "EUR", "€": "EUR", "ЕВРО": "EUR",
}
_CUR_STRIP = re.compile(r"[\s.]+")


def map_currency(value) -> str | None:
    """Значение валюты поставщика -> RUB/USD/EUR; None, если не распознано/пусто."""
    if value is None:
        return None
    s = _CUR_STRIP.sub("", str(value)).upper()
    if not s:
        return None
    return _CURRENCY.get(s)


